/** Translate an English UI string to the current language (S.lang) and fill its {placeholders}. */
function t(text, params) {
  const lang = typeof S !== "undefined" ? S.lang : null;
  const s = (lang && I18N[lang] && I18N[lang][text]) || text;
  return params ? s.replace(/\{(\w+)\}/g, (m, k) => (k in params ? params[k] : m)) : s;
}
